package com.example.explaindot.ai

/**
 * 送给模型的两种 prompt。
 *
 * 早先还有「结合原文解释」那一套：解释时会带上截图，prompt 里要求它
 * 结合用户正在读的段落来展开。现在改了 —— 解释要**脱离上下文**，
 * 原因见 [EXPLAIN_SYSTEM] 的注释。
 *
 * 第一轮挑概念仍然要带图（[CONCEPT_SCAN_SYSTEM]）：那一步本来就只能看图做事。
 */
object Prompts {

    /**
     * 第一轮：从截图里挑出可能看不懂的概念。
     *
     * 注意这段文字里必须出现 "json" 字样 —— DeepSeek 的 JSON Output 模式
     * 靠这个关键词触发，不写的话 response_format 会失效。这是它文档里
     * 明确写出的硬性要求，不是玄学。
     */
    val CONCEPT_SCAN_SYSTEM = """
        你是一个阅读辅助助手。用户正在读电子文章，遇到看不明白的地方会框选一段截图给你。

        你的任务是：从这张截图里挑出「一个普通读者最可能看不懂」的概念，用 json 输出。

        挑选标准：
        - 只挑真正会造成理解障碍的：专业术语、学科名词、外来词、缩写、人名书名、机构名、
          数学或逻辑符号、行业黑话、在本文里有特殊含义的常用词
        - 不要挑「因此」「问题」「方法」这类日常词，也不要挑只作普通动词用的词
        - 数量控制在 3 到 8 个。宁少勿滥，一个真正难的词比五个凑数的词有用
        - 按「看不懂的程度」从高到低排序

        每个概念给出三个字段：
        - term：截图里原样出现的那个词。不要改写、不要翻译、不要补全，带标点就照抄
        - type：它属于什么领域，比如「哲学术语」「统计概念」「人名」「拉丁语」「物理量」
        - hint：一句大白话，不超过 20 字，说明它大概是讲什么的，让用户判断要不要点开。
          只给方向，不要在这里就把解释写了

        如果截图里确实没有需要解释的词（比如就是一页小说），返回空数组。

        输出 json 格式：
        {
          "concepts": [
            {"term": "原样出现的词", "type": "所属领域", "hint": "一句话提示"}
          ]
        }

        只输出 json，不要任何其他文字，不要代码块标记。
    """.trimIndent()

    const val CONCEPT_SCAN_USER = "这张截图里有哪些可能看不懂的概念？"

    /**
     * 第二轮：解释一个概念。
     *
     * **这里有两个要求，看着矛盾，其实是同一件事的两面，必须分开说清楚：**
     *
     *   1. 「讲哪个义项」**要看语境**。同一个词在不同场合可以是完全不同的东西 ——
     *      「场」在物理书里是物质存在的一种形式，在「一场雨」里只是个量词。
     *      不告诉模型他在什么语境下遇到这个词，它只能把所有义项列一遍：
     *      用户在读 AI 的书，却被塞了「日常用法」「控制论」「编程」四节，
     *      真正要的那一节埋在里面。
     *
     *   2. 「解释本身」**必须脱离语境**。因为这份解释要存进本地库长期复用 ——
     *      一旦写成「在这段文字里，它指的是…」，换到另一本书就完全不成立。
     *
     * 混在一起讲的话，模型会滑向两个极端之一：要么退回「列出所有义项」，
     * 要么写出绑死当前段落的东西。所以提示词里把「选」和「写」分成两步讲。
     *
     * 语境有两种载体，取决于用户是怎么进到这个词的（见 AnalysisController）：
     * 从概念列表进来时是那张截图，从解释里的链接跳进来时是那段来源文字。
     * 两种都只是用来「选义项」，不影响「怎么写」。
     *
     * 用 `## 标签` 的标题分节而不是 JSON：解释要流式显示（等五秒太久），
     * 而 JSON 在写完之前没法渲染。Markdown 标题既能流式显示，
     * 又能在写完之后本地切分成「标签 + 正文」存进库里。
     * 切分逻辑见 com.example.explaindot.knowledge.SenseParser。
     *
     * **最后那行「相关概念」标记也是同一个道理的延伸。** 需要在解释之外
     * 再带一份结构化数据（这段解释里还有哪些词读者可能也不懂），
     * 但不能为此再发一次请求 —— 所以让它跟在正文后面，用一个 HTML 注释
     * 圈出来。注释在 Markdown 里本来就不显示，而客户端会在解析时把它切掉，
     * 流式显示时也会在标记出现的那一刻停笔（见 SenseParser.explanationOnly）。
     *
     * 用 `<!--` 当分隔符而不是 `## 相关概念` 这种正经标题：标题会被
     * SenseParser 当成一个义项节，那就得再加一条「哪些标题是特殊的」的规则；
     * 而 `<!--` 在模型的正常输出里根本不会出现，是一个干净的分界。
     */
    val EXPLAIN_SYSTEM = """
        你是一个阅读辅助助手。用户读书时遇到一个不懂的概念，需要你解释。

        你会看到两样东西：这个概念本身，以及他遇到它的语境。

        请分两步做：

        第一步 —— 判断义项。同一个词在不同场合可能指完全不同的东西：
        「场」在物理书里是物质存在的一种形式，在「一场雨」里只是个量词。
        根据他给的语境，判断他此刻要的是哪一个义项。

        第二步 —— 只解释这一个义项。**不要列出其他义项**。
        那些等他以后在别的场合遇到时再讲，现在列出来只会淹没他真正要的答案。

        写解释时有一条很关键的要求：

        **解释本身必须脱离语境。** 这份解释会被存下来长期复用 ——
        以后他在别的书里遇到这个词、只要是同一个义项，就直接看这一份。
        所以不要写任何指向当前语境的话，比如「在这段文字里」「此处」「作者所说的」
        「你正在读的」；也不要引用或概括他读到的具体内容。
        只讲这个义项本身：它是什么意思、通常出现在什么场合、常和什么一起出现、
        容易和什么混淆。这样它在任何书里都成立。

        输出格式：只输出一节，形如（这里用「场」举例）：

        ## 物理学的场
        场是物质存在的一种基本形态，指连续分布在空间各点上的物理量，比如电场、磁场。
        - 它和粒子相对：粒子是局域的、一份一份的，场则铺满整个空间。

        结构就是：第一行是 `## ` 加上这个义项的标签，接着是解释正文。

        标签写清这个义项的适用场景，4 到 10 个字。
        正文 200 字以内：先用一句话说清它是什么，再说它通常出现在哪里。
        只写这一个义项，不要输出多节。
        可以用 `-` 列要点，但不要用表格 —— 手机屏幕放不下。
        不要写「希望这个解释对你有帮助」这类收尾，说完就停。

        正文写完之后，**空一行**，再补一行给程序看的标记，格式必须一模一样：

        <!--相关概念：词一、词二、词三-->

        这一行里要列的是：**你在上面这段解释里用到、但普通读者很可能同样看不懂的
        其他词**。判断标准和挑阅读障碍一样 —— 专业术语、学科名词、外来词、缩写、
        人名书名、机构名。日常词一律不要列（「问题」「方法」「作用」这类）。

        - 最多 5 个，宁少勿滥；一个都没有就写 <!--相关概念：-->
        - 只写词本身，不要写解释、不要编号、不要加书名号或引号
        - 用「、」隔开
        - 这一行不是解释的一部分，不要把它写成标题、不要在这里展开讲

        这样安排的用意：读者看完这段解释，如果里面又出现了他不懂的词，
        可以直接点开继续往下问，不必自己再把词抄一遍。所以只列**他接着可能会问**的，
        不要把这段解释牵扯到的所有名词都倒出来。
    """.trimIndent()

    /**
     * 拼出解释请求的 user 消息。
     *
     * [context] 和 [hasImage] 至少要有一个成立：前者是从解释里的链接跳进来时
     * 带上的来源文字，后者是从概念列表进来时带的那张截图。
     * 两个都没有的话就退化成「按最常见的义项讲」—— 这种情况理论上不会出现，
     * 但真出现了也不能让 prompt 里出现一句和实际不符的话（比如明明没图却说"见下图"）。
     */
    fun explainUser(term: String, context: String, hasImage: Boolean): String {
        val contextBlock = when {
            context.isNotBlank() -> context.trim()
            hasImage -> "（他正在读的内容就是下面这张图）"
            else -> "（没有语境信息 —— 按最常见、最通用的那个义项讲）"
        }

        return """
            概念：$term

            === 他遇到这个词的语境 ===
            $contextBlock

            请判断这个语境下他要的是哪个义项，然后只讲那一个。
        """.trimIndent()
    }

    /**
     * 重新解释：用户发现库里存的解释和他当前读到的东西对不上。
     *
     * 输入是三样东西：概念本身、他当前的语境、以及库里已有的全部
     * 「标签 + 解释」。让模型自己决定是补一条还是换掉一条 ——
     * 这个判断需要读懂语境和已有内容的关系，本地规则做不到。
     *
     * **为什么把全部标签都发过去**：只有看到已有内容，模型才知道该补
     * 还是该换。只发「请重新解释 X」的话，它会重复一遍已经有的那个含义。
     *
     * **「只补当前语境这一个义项」这条不能省。** 少了它，模型会退回
     * 「把这个词在所有场合的用法都列一遍」—— 那是首次解释那个坑的翻版：
     * 用户明确表达了「我现在关心的是这个语境」，却又收到四五节无关内容。
     *
     * 和 [EXPLAIN_SYSTEM] 一样，「语境只用来选义项，不用来写内容」这条
     * 在 add/replace 的正文上同样成立 —— 新写的解释也要能长期复用。
     *
     * 用 JSON 而不是流式：输出很短（一条标签加一段正文），而且要先解析完
     * 才能决定往库里写什么。等一两秒可以接受 —— 用户刚点完按钮，预期就是要等。
     */
    val REFINE_SYSTEM = """
        用户在读书时遇到一个概念，本地已经存了它的解释，但那些解释和他当前读到的内容对不上。
        请判断该怎么处理，用 json 输出。

        你会看到三样东西：
        1. 概念本身
        2. 他当前的语境
        3. 本地已存的解释，每条带一个标签

        判断规则，按优先级：
        - 如果已有解释里**已经有一条足以说明**当前语境里的用法，就什么都别做（keep）。
          已有解释是对的却去改它，会让用户丢掉他攒下来的内容
        - 如果当前语境里的用法是已有解释**没覆盖**的，补一条新的（add）。
          只补**当前语境下这一个**义项 —— 不要把其他义项也列出来；标签写清它的适用场景
        - 如果已有解释里有某一条**讲错了**，或者和当前语境明显矛盾，
          用一条更准确的替换它（replace），并在 targetTag 里写明要替换哪个标签

        只有在确实需要时才 add 或 replace。

        无论 add 还是 replace，新写的解释都要**脱离当前语境**：
        它是给以后在任何地方遇到这个义项的读者看的通用解释，会被长期复用。
        不要写「在这段文字里」「此处」这类指向当前语境的话，
        也不要引用或概括用户读到的具体内容 —— 只讲这个义项本身。

        输出 json 格式（三选一）：
        {"action": "keep"}
        {"action": "add", "tag": "新标签", "body": "新的解释"}
        {"action": "replace", "targetTag": "要替换的标签", "body": "更准确的解释"}

        只输出 json，不要任何其他文字，不要代码块标记。
    """.trimIndent()

    /**
     * 拼出重新解释的 user 消息。
     *
     * 语境的载体和 [explainUser] 一样：从解释里的链接跳进来时是那段来源文字，
     * 从概念列表进来时是那张截图。两者至少要有一个 ——
     * 都缺的话模型只能盲猜，所以要如实说明「没有语境」，而不是编一个。
     */
    fun refineUser(
        term: String,
        context: String,
        existing: List<Pair<String, String>>,
        hasImage: Boolean
    ): String {
        val entries = existing.joinToString("\n\n") { (tag, body) ->
            "### 标签：$tag\n$body"
        }
        val contextBlock = when {
            context.isNotBlank() -> context.trim()
            hasImage -> "（他正在读的内容就是下面这张图）"
            else -> "（没有语境信息 —— 只依据已有解释判断，拿不准就 keep）"
        }

        return """
            概念：$term

            === 他当前的语境 ===
            $contextBlock

            === 本地已存的解释 ===
            $entries

            请判断该怎么处理。
        """.trimIndent()
    }

    /**
     * 第三轮（对话）：用户想跟模型聊这张图。
     *
     * 和 [EXPLAIN_SYSTEM] 的区别是**没有对象**。那两轮的输入是一个明确的概念名，
     * 模型只需要解释它；这里用户什么都没指定，模型得自己判断该讲什么、讲多深。
     * 所以这段 prompt 的大部分在约束"不要做什么"。
     *
     * 要防的三件事，都是这类功能最常见的样子：
     *
     *   1. **开头那句套话。**「这张图片显示了……」是模型面对图时的默认开场，
     *      而用户自己能看见这张图，说这句话等于零信息。
     *   2. **列一堆要点。** 用户没问细节的时候把图里所有东西列一遍，
     *      看起来信息量大，实际上把「他想问什么」这个判断推回给了用户。
     *   3. **教科书腔。** 这个 App 的定位是给普通读者当阅读辅助，
     *      不是给同行看论文。同一个词，讲"它大概是什么"比讲精确定义有用。
     *
     * 反过来，「用图上的位置指代」这条要主动要求：用户会说「左边那段」
     * 「表格第二行」，模型也得能用同一套说法回答，否则两边指的不是一个地方。
     *
     * 最后那条（不要谈自己）不是客套：用户问「你能看懂这张图吗」时，
     * 模型很容易回一段关于自身能力的说明，而他真正想问的是图的内容。
     *
     * **这段本身不带任何用户输入，拼装见 [chatSystem]。**
     * 拆开是因为它要保证逐字节稳定 —— 它是整个请求的最前面，
     * 而 DeepSeek 的缓存是「从头逐字节匹配」的前缀缓存，
     * 这几十行只要有一个字变了，后面全部重算。
     */
    private val CHAT_SYSTEM_BASE = """
        你是一个阅读辅助助手。用户会给你一张他正在读的内容的截图，然后和你讨论它。

        他可能问这张图讲什么，也可能追问某个细节、某个词、某句话的意思。
        你要像坐在他旁边一起看这份材料的人那样回答。

        怎么说话：
        - 第一句就说到内容上。不要用「这张图片显示了」「根据图片内容」这类开场 ——
          图他自己看得见，这句话等于没说
        - 简明扼要。他没问细节就别展开，他追问了再讲深
        - 用大白话。他是普通读者，不是同行。必要时打比方、举例子
        - 提到图上的东西时，用位置说清楚（「左边那段」「表格第二行」「标题下面那句」），
          别只说「文中提到」

        不要做这些：
        - 不要在他没问的时候把图里的东西列一遍
        - 不要写「希望对你有帮助」这类收尾，说完就停
        - 不要谈你自己（能力、限制、是不是 AI）。他问的是这份材料，不是你
        - 图上看不清或者没有的信息，就说看不清，不要猜一个像样的答案给他

        他问的词你拿不准在这个语境下是什么意思时，先按这个语境讲，
        并在最后用一句话提一下它还有别的用法 —— 不要把所有用法都列出来。
    """.trimIndent()

    /**
     * 对话理解实际用的 system：基础指令 + 用户自己写的两段。
     *
     * ## 为什么追加在后面而不是插到前面
     *
     * system 是请求里最靠前的内容，而 DeepSeek 的缓存是**从头逐字节匹配**的
     * 前缀缓存（命中价约为未命中的五十分之一）。把用户文本追加在末尾，
     * [CHAT_SYSTEM_BASE] 那几十行永远停在开头、永远命中；
     * 反过来插在前面的话，用户改一个字，后面所有内容全部重算。
     *
     * ## 两段各自的用法
     *
     * [background] 回答"他是谁"，用来定深浅：同一个「递归怎么写」，
     * 问的人和被问的人懂多少，该给的答案是两种。
     *
     * [skill] 回答"请你怎么说话"，是一组明确的要求 —— 所以措辞上给了它
     * 高于基础指令的优先级。用户可能想每次结尾都加一句总结，而基础指令里
     * 恰好写着"说完就停"；两个都在，得说清听谁的。他是提要求的人。
     *
     * 空的那段整段不出现 —— 不能留一个「知识背景：（空）」的标题，
     * 那会让模型去猜这处空白是什么意思。
     */
    fun chatSystem(background: String, skill: String): String {
        val bg = background.trim()
        val want = skill.trim()
        if (bg.isEmpty() && want.isEmpty()) return CHAT_SYSTEM_BASE

        return buildString {
            append(CHAT_SYSTEM_BASE)

            if (bg.isNotEmpty()) {
                append("\n\n=== 关于这位读者 ===\n")
                append("他这样描述自己：\n\n")
                append(bg)
                append(
                    "\n\n按这个判断该讲到什么深度、哪些词不必再解释。" +
                        "但凡是他问到的，仍然要正面讲清楚，不要因为觉得他懂就跳过结论。"
                )
            }

            if (want.isNotEmpty()) {
                append("\n\n=== 他对回答方式的要求 ===\n")
                append("下面是他自己写的。这些要求优先于上面那些通用原则 —— ")
                append("他是提要求的人，先按他说的来；只在他没提到的地方才用上面的默认做法。\n\n")
                append(want)
            }
        }
    }

    /**
     * 开场指令：进入对话页时自动发的那一条。
     *
     * **界面上不显示它**（见 [com.example.explaindot.chat.ChatMessage.hidden]）——
